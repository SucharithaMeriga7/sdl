                NEW_WATERMARK,
                SOURCE_COUNT,
                INSERTED_COUNT,
                UPDATED_COUNT,
                DECOMMISSIONED_COUNT,
                STATUS,
                ERROR_MESSAGE
            ) VALUES (
                v_run_id,
                v_run_timestamp,
                v_watermark,
                NULL,
                v_source_count,
                0,
                0,
                0,
                v_status,
                v_error_message
            );
        EXCEPTION
            WHEN OTHER THEN
                NULL;   -- Suppress secondary logging error; surface original below
        END;

        RETURN OBJECT_CONSTRUCT(
            'error',       v_error_message,
            'run_id',      v_run_id,
            'status',      v_status
        )::VARCHAR;

END;
