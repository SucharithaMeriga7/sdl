                    Implements: watermark-based incremental load, deduplication by UPDATED_AT,
                    CamelCase MANUFACTURER, WEIGHT_KG null-guard, SUPPLY_RISK_LEVEL derivation,
                    soft delete (Decommissioned), mandatory ETL_RECONCILIATION_LOG per run.
